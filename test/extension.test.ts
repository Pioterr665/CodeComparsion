import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {activate} from '../src/extension';
import * as mock from './vscode-mock';
const uri=(p:string)=>new mock.Uri(p);
const call=async(id:string,...args:any[])=>mock.commandsMap.get('codecomparsion.'+id)!(...args);
test('context selection, native diff, recursive results and row activation',async()=>{
 const context={subscriptions:[]} as any;activate(context);
 const manifest=JSON.parse(readFileSync('package.json','utf8'));
 assert.deepEqual([...mock.commandsMap.keys()].sort(),manifest.contributes.commands.map((c:any)=>c.command).sort());
 mock.nodes.set('/a',{type:1,content:'old'});mock.nodes.set('/b',{type:1,content:'new'});
 await call('select',uri('/a'));await call('compare',uri('/b'));
 assert.ok(mock.executed.some(c=>c[0]==='setContext'&&c[2]===true));
 assert.ok(mock.executed.some(c=>c[0]==='vscode.diff'&&c[1].path==='/a'&&c[2].path==='/b'));
 mock.nodes.set('/l',{type:2});mock.nodes.set('/r',{type:2});
 mock.nodes.set('/l/deep',{type:2});mock.nodes.set('/r/deep',{type:2});
 mock.nodes.set('/l/deep/file',{type:1,content:'left'});mock.nodes.set('/r/deep/file',{type:1,content:'right'});
 await call('select',uri('/l'));await call('compare',uri('/r'));
 const row=mock.provider.rows.find((r:any)=>r.path==='deep/file');assert.equal(row.path,'deep/file');assert.equal(row.status,'modified');
 const item=mock.provider.getTreeItem(row);assert.equal(item.command.command,'codecomparsion.open');
 assert.ok(mock.panels[0].webview.html.includes('Aligned folder comparison'));
 await mock.panels[0].message({type:'open',path:'../../outside'});
 const before=mock.executed.length;
 await mock.panels[0].message({type:'open',path:'deep/file'});
 assert.equal(mock.executed[before][0],'vscode.diff');
 await call('open',row);
 assert.ok(mock.executed.some(c=>c[0]==='vscode.diff'&&c[1].path==='/l/deep/file'&&c[2].path==='/r/deep/file'));
 mock.nodes.set('/r/deep/file',{type:1,content:'left'});await call('refresh');assert.equal(mock.provider.rows.find((r:any)=>r.path==='deep/file').status,'equal');
 await call('select',uri('/a'));await call('compare',uri('/r'));assert.ok(mock.errors.some(e=>e.includes('same type')));
 mock.nodes.set('/link',{type:65});await call('select',uri('/link'));await call('compare',uri('/b'));assert.ok(mock.errors.some(e=>e.includes('Symbolic')));
 for(const d of context.subscriptions)d.dispose();
});
